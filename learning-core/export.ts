/**
 * The single user-facing export: Markdown + saved image ZIP — docs/v2/storage.md §6.
 *
 * Readable by tools like Obsidian; NOT a lossless AnnHub database restore.
 * Environment-neutral: the host passes entries + an asset reader; this
 * module derives the file set, YAML frontmatter (via a serializer, never
 * hand-built), relative image links and the missing-asset manifest. Section
 * headings follow the interface language the export was started in; keys,
 * frontmatter fields and paths never change with it.
 */
import { writeHighlightMarks } from './markdown'
import { BUILTIN_PROPERTY_DEFINITIONS, propertyStorageKey } from './properties'
import { buildZip, type ZipEntry } from './zip'
import { sha256Hex } from './assets'
import type { EntryRecord, ImageAsset, PropertyDefinition, PropertyValue } from './types'

export type ExportLanguage = 'zh' | 'en'

export interface ExportAsset {
  metadata: ImageAsset
  bytes: Uint8Array | Blob
}

export interface ExportInput {
  exportedAt: number
  lang: ExportLanguage
  entries: EntryRecord[]
  registry: PropertyDefinition[]
  /** Reads one saved asset; `undefined` marks it missing (partial export). */
  readAsset: (assetId: string) => Promise<ExportAsset | undefined>
}

export interface ExportSummary {
  result: 'full' | 'partial'
  clips: number
  screenshots: number
  missingAssets: string[]
  blob: Blob
}

